"""Paper numbers for the visual-interaction runs, restricted to the reported conditions (rule_1, rule_2).

Usage: PYTHONPATH=. python cvpr2027/tmp/paper_numbers.py [model ...]
Reads ledgers only; writes nothing.
"""
import json
import os
import random
import sys
from collections import defaultdict
from pathlib import Path

RULES = ('rule_1', 'rule_2')
BASE = Path(os.environ.get('VI_RESULTS', 'results/visual_interaction'))
ARMS = ('none', 'own', 'own_record', 'observations', 'sibling', 'law_text')


def boot(rows, stat, n=2000, seed=0):
    by = defaultdict(list)
    for r in rows:
        by[r['world']].append(r)
    keys, rng, vals = list(by), random.Random(seed), []
    for _ in range(n):
        vals.append(stat([r for k in (rng.choice(keys) for _ in keys) for r in by[k]]))
    vals.sort()
    return vals[int(.025 * n)], vals[int(.975 * n)]


def acc(rows):
    return sum(r['correct'] for r in rows) / len(rows) if rows else float('nan')


def model_numbers(model, mode='frames_predict'):
    d = BASE / model / mode
    if not (d / 'exam.jsonl').exists():
        return None
    rows = [json.loads(l) for l in open(d / 'exam.jsonl') if l.strip()]
    rows = [dict(r, world=(r['group'], r['rule'], r['variant'])) for r in rows
            if r.get('status') == 'complete' and r['rule'] in RULES]
    out = {'exam': {}, 'paired': {}, 'curve': {}, 'worlds': len({r['world'] for r in rows if r['evidence'] == 'own'})}
    idx = {}
    for arm in ARMS:
        for rule in (None,) + RULES:
            R = [r for r in rows if r['evidence'] == arm and (rule is None or r['rule'] == rule)]
            if not R:
                continue
            lo, hi = boot(R, acc)
            e = dict(n=len(R), acc=acc(R), ci=(lo, hi), canonical=sum(r['picked_canonical'] for r in R) / len(R))
            if arm == 'sibling':
                S = [r for r in R if r.get('sibling_answer')]
                e['picked_sibling'] = sum(bool(r['picked_sibling']) for r in S) / max(1, len(S))
            out['exam'][f'{arm}|{rule or "all"}'] = e
        idx[arm] = {(*r['world'], r['item']): r for r in rows if r['evidence'] == arm}
    for x, y in (('own', 'none'), ('own', 'sibling'), ('observations', 'own'), ('own_record', 'observations'),
                 ('own_record', 'own'), ('own_record', 'none'), ('law_text', 'none'), ('law_text', 'own'),
                 ('law_text', 'own_record')):
        keys = sorted(set(idx.get(x, {})) & set(idx.get(y, {})))
        if keys:
            P = [dict(world=k[:3], correct=idx[x][k]['correct'] - idx[y][k]['correct']) for k in keys]
            out['paired'][f'{x}-{y}'] = dict(n=len(P), diff=acc(P), ci=boot(P, acc))
    pts = defaultdict(list)
    for p in sorted((d / 'episodes').glob('*/episode.json')):
        ep = json.loads(p.read_text())
        w = ep['world']
        if w['rule'] not in RULES or ep.get('status') != 'complete':
            continue
        for e in ep['events']:
            if e['kind'] == 'checkpoint':
                pts[e['index']].append(dict(correct=e['correct'], world=(w['group'], w['rule'], w['variant']), rule=w['rule']))
    for k, v in sorted(pts.items()):
        out['curve'][k] = dict(n=len(v), acc=acc(v), ci=boot(v, acc),
                               **{r: acc([x for x in v if x['rule'] == r]) for r in RULES})
    return out


MACRO = {'gpt-6.1-sol': 'GptSol', 'qwen3.8-max': 'Qwen', 'gemini-3.8-flash': 'Gemini',
         'claude-opus-5-5': 'Opus', 'kimi-k3': 'Kimi'}
ARM_MACRO = {'none': 'None', 'own': 'Own', 'own_record': 'OwnRecord', 'observations': 'Obs', 'sibling': 'Sib',
             'law_text': 'Law'}
RULE_MACRO = {'all': '', 'rule_1': 'Struct', 'rule_2': 'Field'}
PAIR_MACRO = {'own-none': 'OwnMinusNone', 'own-sibling': 'OwnMinusSib', 'observations-own': 'ObsMinusOwn',
              'own_record-observations': 'OwnRecordMinusObs', 'own_record-own': 'OwnRecordMinusOwn',
              'own_record-none': 'OwnRecordMinusNone', 'law_text-none': 'LawMinusNone',
              'law_text-own': 'LawMinusOwn', 'law_text-own_record': 'LawMinusOwnRecord'}


def tex(models, path):
    """\\newcommand per number, e.g. \\GptSolOwnAcc, \\GptSolOwnStructAcc, \\GptSolOwnMinusNone."""
    pct = lambda x: f'{100 * x:.1f}'
    lines = ['% Generated by cvpr2027/tmp/paper_numbers.py; do not edit by hand.']
    for m in models:
        res, M = model_numbers(m), MACRO.get(m)
        if res is None or M is None:
            continue
        for k, v in res['exam'].items():
            arm, rule = k.split('|')
            name = f'{M}{ARM_MACRO[arm]}{RULE_MACRO[rule]}'
            lines += [f'\\newcommand{{\\{name}Acc}}{{{pct(v["acc"])}}}',
                      f'\\newcommand{{\\{name}N}}{{{v["n"]}}}',
                      f'\\newcommand{{\\{name}CI}}{{[{pct(v["ci"][0])}, {pct(v["ci"][1])}]}}',
                      f'\\newcommand{{\\{name}Canon}}{{{pct(v["canonical"])}}}']
            if 'picked_sibling' in v:
                lines.append(f'\\newcommand{{\\{name}PickSib}}{{{pct(v["picked_sibling"])}}}')
        for k, v in res['paired'].items():
            if k in PAIR_MACRO:
                name = f'{M}{PAIR_MACRO[k]}'
                lines += [f'\\newcommand{{\\{name}}}{{{100 * v["diff"]:+.1f}}}',
                          f'\\newcommand{{\\{name}CI}}{{[{100 * v["ci"][0]:+.1f}, {100 * v["ci"][1]:+.1f}]}}']
        for k, v in res['curve'].items():
            lines.append(f'\\newcommand{{\\{M}Cp{"ABCD"[int(k)]}}}{{{pct(v["acc"])}}}')
        lines.append(f'\\newcommand{{\\{M}Worlds}}{{{res["worlds"]}}}')
    Path(path).write_text('\n'.join(lines) + '\n')
    print(f'wrote {path} ({len(lines) - 1} macros)')


def main(models):
    if models and models[0] == '--tex':
        path, models = models[1], models[2:] or list(MACRO)
        return tex(models, path)
    for m in models:
        res = model_numbers(m)
        if res is None:
            print(f'== {m}: no exam ledger'); continue
        print(f'== {m}')
        for k, v in res['exam'].items():
            print(f"  exam {k:22s} n={v['n']:4d} acc={100*v['acc']:5.1f} [{100*v['ci'][0]:.1f}, {100*v['ci'][1]:.1f}] "
                  f"canon={100*v['canonical']:.1f}" + (f" sib={100*v['picked_sibling']:.1f}" if 'picked_sibling' in v else ''))
        for k, v in res['paired'].items():
            print(f"  paired {k:24s} n={v['n']:4d} diff={100*v['diff']:+5.1f} [{100*v['ci'][0]:+.1f}, {100*v['ci'][1]:+.1f}]")
        for k, v in res['curve'].items():
            print(f"  checkpoint {k}: n={v['n']} acc={100*v['acc']:.1f} [{100*v['ci'][0]:.1f}, {100*v['ci'][1]:.1f}] "
                  + ' '.join(f"{r}={100*v[r]:.1f}" for r in RULES))


if __name__ == '__main__':
    main(sys.argv[1:] or [p.name for p in sorted(BASE.iterdir()) if p.is_dir()])
